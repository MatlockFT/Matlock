import fs from 'node:fs/promises';

const CHECK_ONLY = process.argv.includes('--check');

const bundles = [
    {
        output: 'assets/site-tail.css',
        sources: [
            'assets/style.css',
            'assets/site-shell.css',
            'assets/site-ticker.css',
            'assets/micro-interactions.css',
            'assets/site-consistency.css'
        ]
    },
    {
        output: 'assets/on-this-day.bundle.css',
        sources: [
            'assets/on-this-day.css',
            'assets/on-this-day-week.css',
            'assets/on-this-day-polish.css',
            'assets/on-this-day-media.css',
            'assets/on-this-day-qol.css',
            'assets/otd-share.css',
            'assets/on-this-day-overhaul.css',
            'assets/dynamic-page-stability.css'
        ]
    }
];

const normalize = value => String(value).replace(/\r\n/g, '\n').trimEnd();

async function renderBundle(bundle) {
    const sections = await Promise.all(bundle.sources.map(async source => {
        const css = normalize(await fs.readFile(source, 'utf8'));
        return `/* Source: ${source} */\n${css}`;
    }));
    return `/* Generated by scripts/build-frontend-bundles.mjs. Do not edit directly. */\n\n${sections.join('\n\n')}\n`;
}

let stale = false;
for (const bundle of bundles) {
    const expected = await renderBundle(bundle);
    if (CHECK_ONLY) {
        const current = await fs.readFile(bundle.output, 'utf8').catch(() => '');
        if (normalize(current) !== normalize(expected)) {
            console.error(`${bundle.output} is stale. Run npm run build:frontend.`);
            stale = true;
        }
        continue;
    }
    await fs.writeFile(bundle.output, expected);
    console.log(`Built ${bundle.output} from ${bundle.sources.length} source files.`);
}

if (stale) process.exitCode = 1;
