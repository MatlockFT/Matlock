import { access, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import sharp from 'sharp';
import { responsiveOutputPlan } from './media-paths.mjs';
import { writeGeneratedIntegrityManifest } from './generated-integrity.mjs';

const root = resolve(import.meta.dirname, '../..');
const postsDirectory = join(root, '_posts');
const postOutputDirectory = join(root, 'assets', 'generated', 'posts');
const siteOutputDirectory = join(root, 'assets', 'generated', 'site');
const manifestPath = join(root, '_data', 'responsive_images.yml');
const targetWidths = [480, 720, 768, 960, 1600];

function yamlString(value) {
    return JSON.stringify(value);
}

function findFeaturedImage(markdown) {
    const frontmatter = markdown.match(/^---\n([\s\S]*?)\n---/);

    if (!frontmatter) {
        return null;
    }

    const imageBlock = frontmatter[1].match(
        /^image:\s*\n((?:^[ \t]+.*(?:\n|$))*)/m
    );

    if (!imageBlock) {
        return null;
    }

    const pathMatch = imageBlock[1].match(/^\s+path:\s*(.+?)\s*$/m);

    return pathMatch
        ? pathMatch[1].replace(/^['"]|['"]$/g, '')
        : null;
}

async function generateSiteHeader() {
    const sourcePath = join(root, 'assets', 'header-image.png');
    const widths = [480, 800];

    for (const width of widths) {
        await sharp(sourcePath)
            .rotate()
            .resize({
                width,
                withoutEnlargement: true
            })
            .webp({
                quality: 82,
                effort: 5
            })
            .toFile(join(siteOutputDirectory, `header-image-${width}.webp`));
    }
}

await mkdir(postOutputDirectory, { recursive: true });
await mkdir(siteOutputDirectory, { recursive: true });
await mkdir(join(root, '_data'), { recursive: true });

const postFiles = (await readdir(postsDirectory))
    .filter(file => file.endsWith('.md'))
    .sort();

const imagePaths = new Set();

for (const file of postFiles) {
    const markdown = await readFile(join(postsDirectory, file), 'utf8');
    const imagePath = findFeaturedImage(markdown);

    if (imagePath) {
        imagePaths.add(imagePath);
    }
}

const manifestEntries = [];

// Drafts may temporarily reference media that has not uploaded yet.
for (const imagePath of [...imagePaths].sort()) {
    const sourcePath = join(root, imagePath.replace(/^\//, ''));
    try {
        await access(sourcePath);
    } catch {
        console.warn(`Skipping missing featured image: ${imagePath}`);
        continue;
    }
    const metadata = await sharp(sourcePath).metadata();

    if (!metadata.width || !metadata.height) {
        throw new Error(`Could not read image dimensions: ${imagePath}`);
    }

    const largestWidth = Math.min(metadata.width, 1600);
    const widths = [
        ...new Set([
            ...targetWidths.filter(width => width < largestWidth),
            largestWidth
        ])
    ].sort((a, b) => a - b);

    const plan = responsiveOutputPlan(imagePath);
    const outputDirectory = join(root, plan.relativeDirectory);
    await mkdir(outputDirectory, { recursive: true });
    const variants = [];

    for (const width of widths) {
        const filename = `${plan.stem}-${width}.webp`;
        const outputPath = join(outputDirectory, filename);

        await sharp(sourcePath)
            .rotate()
            .resize({
                width,
                withoutEnlargement: true
            })
            .webp({
                quality: 78,
                effort: 5
            })
            .toFile(outputPath);

        variants.push({
            width,
            url: `${plan.publicDirectory}/${filename}`
        });
    }

    const largest = variants.at(-1);
    const smallest = variants[0];

    manifestEntries.push({
        imagePath,
        width: metadata.width,
        height: metadata.height,
        src: largest.url,
        small: smallest.url,
        srcset: variants
            .map(variant => `${variant.url} ${variant.width}w`)
            .join(', ')
    });
}

const manifest = [
    '# Generated by npm run optimize:images. Do not edit by hand.',
    ...manifestEntries.flatMap(entry => [
        `${yamlString(entry.imagePath)}:`,
        `  width: ${entry.width}`,
        `  height: ${entry.height}`,
        `  src: ${yamlString(entry.src)}`,
        `  small: ${yamlString(entry.small)}`,
        `  srcset: ${yamlString(entry.srcset)}`
    ]),
    ''
].join('\n');

await writeFile(manifestPath, manifest);
await generateSiteHeader();
await writeGeneratedIntegrityManifest();

console.log(
    `Generated responsive variants for ${manifestEntries.length} featured images plus the site header.`
);
