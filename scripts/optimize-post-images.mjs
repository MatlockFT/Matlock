import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { basename, extname, join, resolve } from 'node:path';
import sharp from 'sharp';

const root = resolve(import.meta.dirname, '..');
const postsDirectory = join(root, '_posts');
const outputDirectory = join(root, 'assets', 'generated', 'posts');
const manifestPath = join(root, '_data', 'responsive_images.yml');
const targetWidths = [480, 960, 1600];

function yamlString(value) {
    return JSON.stringify(value);
}

function findFeaturedImage(markdown) {
    const frontmatter = markdown.match(/^---\n([\s\S]*?)\n---/);

    if (!frontmatter) {
        return null;
    }

    const imageBlock = frontmatter[1].match(
        /^image:\s*\n((?:^[ \t]+.*(?:\n|$))*)/m
    );

    if (!imageBlock) {
        return null;
    }

    const pathMatch = imageBlock[1].match(/^\s+path:\s*(.+?)\s*$/m);

    return pathMatch
        ? pathMatch[1].replace(/^['"]|['"]$/g, '')
        : null;
}

function outputStem(imagePath) {
    const extension = extname(imagePath);

    return imagePath
        .slice(1, -extension.length)
        .replace(/^assets\//, '')
        .replaceAll('/', '-')
        .replace(/[^a-zA-Z0-9_-]+/g, '-')
        .replace(/-+/g, '-')
        .toLowerCase();
}

await mkdir(outputDirectory, { recursive: true });
await mkdir(join(root, '_data'), { recursive: true });

const postFiles = (await readdir(postsDirectory))
    .filter(file => file.endsWith('.md'))
    .sort();

const imagePaths = new Set();

for (const file of postFiles) {
    const markdown = await readFile(join(postsDirectory, file), 'utf8');
    const imagePath = findFeaturedImage(markdown);

    if (imagePath) {
        imagePaths.add(imagePath);
    }
}

const manifestEntries = [];

for (const imagePath of [...imagePaths].sort()) {
    const sourcePath = join(root, imagePath.replace(/^\//, ''));
    const metadata = await sharp(sourcePath).metadata();

    if (!metadata.width || !metadata.height) {
        throw new Error(`Could not read image dimensions: ${imagePath}`);
    }

    const largestWidth = Math.min(metadata.width, 1600);
    const widths = [
        ...new Set([
            ...targetWidths.filter(width => width < largestWidth),
            largestWidth
        ])
    ].sort((a, b) => a - b);

    const stem = outputStem(imagePath);
    const variants = [];

    for (const width of widths) {
        const filename = `${stem}-${width}.webp`;
        const outputPath = join(outputDirectory, filename);

        await sharp(sourcePath)
            .rotate()
            .resize({
                width,
                withoutEnlargement: true
            })
            .webp({
                quality: 78,
                effort: 5
            })
            .toFile(outputPath);

        variants.push({
            width,
            url: `/assets/generated/posts/${filename}`
        });
    }

    const largest = variants.at(-1);
    const smallest = variants[0];

    manifestEntries.push({
        imagePath,
        width: metadata.width,
        height: metadata.height,
        src: largest.url,
        small: smallest.url,
        srcset: variants
            .map(variant => `${variant.url} ${variant.width}w`)
            .join(', ')
    });
}

const manifest = [
    '# Generated by npm run optimize:images. Do not edit by hand.',
    ...manifestEntries.flatMap(entry => [
        `${yamlString(entry.imagePath)}:`,
        `  width: ${entry.width}`,
        `  height: ${entry.height}`,
        `  src: ${yamlString(entry.src)}`,
        `  small: ${yamlString(entry.small)}`,
        `  srcset: ${yamlString(entry.srcset)}`
    ]),
    ''
].join('\n');

await writeFile(manifestPath, manifest);

console.log(
    `Generated responsive variants for ${manifestEntries.length} featured images.`
);
