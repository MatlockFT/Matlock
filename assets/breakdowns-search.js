/* Full-text filtering for the public Breakdowns archive.
   Article text is generated by Jekyll and fetched only when search is used. */
(() => {
    'use strict';

    function normalizeText(value) {
        return String(value || '')
            .normalize('NFKD')
            .replace(/\p{M}/gu, '')
            .toLocaleLowerCase('en')
            .replace(/[^\p{L}\p{N}]+/gu, ' ')
            .replace(/\s+/g, ' ')
            .trim();
    }

    function initArchiveSearch() {
        const archive = document.querySelector('[data-archive-index-url]');
        if (!archive) return;

        const search = archive.querySelector('[data-archive-search]');
        const category = archive.querySelector('[data-archive-category]');
        const year = archive.querySelector('[data-archive-year]');
        const status = archive.querySelector('[data-archive-status]');
        const empty = archive.querySelector('[data-archive-empty]');
        const grid = archive.querySelector('[data-archive-grid]');
        const cards = [...archive.querySelectorAll('[data-archive-card]')];

        if (!search || !category || !year || !status || !empty || !grid) return;

        // Index public metadata immediately; keep the lengthy article text out of the HTML.
        const entries = cards.map(card => ({
            card,
            key: card.dataset.archiveKey || '',
            category: card.dataset.category || '',
            year: card.dataset.year || '',
            metadata: normalizeText([
                card.dataset.title,
                card.dataset.summary,
                card.dataset.tags,
                card.dataset.category,
                card.dataset.year
            ].join(' '))
        }));

        let bodies = null;
        let indexPromise = null;
        let indexFailed = false;

        function render() {
            const words = normalizeText(search.value).split(' ').filter(Boolean);
            const selectedCategory = category.value;
            const selectedYear = year.value;
            const loading = words.length > 0 && !bodies && !indexFailed;
            let visible = 0;

            entries.forEach(entry => {
                const matchesTerms = words.every(word =>
                    entry.metadata.includes(word) ||
                    (bodies && (bodies.get(entry.key) || '').includes(word))
                );
                const matches = matchesTerms &&
                    (!selectedCategory || entry.category === selectedCategory) &&
                    (!selectedYear || entry.year === selectedYear);

                entry.card.hidden = !matches;
                if (matches) visible += 1;
            });

            grid.setAttribute('aria-busy', loading ? 'true' : 'false');
            empty.hidden = loading || visible !== 0;
            if (loading) {
                status.textContent = 'Searching all article text…';
            } else {
                const noun = visible === 1 ? 'article' : 'articles';
                status.textContent = 'Showing ' + visible + ' ' + noun + '.' +
                    (words.length && indexFailed ? ' Full-text search temporarily unavailable; matching titles and summaries.' : '');
            }
        }

        function loadIndex() {
            if (bodies || indexPromise || indexFailed) return;
            indexPromise = fetch(archive.dataset.archiveIndexUrl, {
                credentials: 'same-origin',
                cache: 'no-cache'
            })
                .then(response => {
                    if (!response.ok) throw new Error('Search index HTTP ' + response.status);
                    return response.json();
                })
                .then(rows => {
                    if (!Array.isArray(rows) || rows.length !== entries.length) {
                        throw new Error('Search index is incomplete');
                    }
                    bodies = new Map(rows.map(row => [
                        String(row.url || ''),
                        normalizeText(row.text)
                    ]));
                    if (entries.some(entry => !bodies.has(entry.key))) {
                        throw new Error('Search index does not match archive');
                    }
                })
                .catch(error => {
                    indexFailed = true;
                    bodies = null;
                    console.warn('Breakdowns full-text search unavailable:', error);
                })
                .finally(() => {
                    indexPromise = null;
                    render();
                });
        }

        function onFilterChange() {
            if (search.value.trim()) loadIndex();
            render();
        }

        search.addEventListener('input', onFilterChange);
        search.addEventListener('keydown', event => {
            if (event.key === 'Escape' && search.value) {
                search.value = '';
                render();
            }
        });
        category.addEventListener('change', onFilterChange);
        year.addEventListener('change', onFilterChange);
        render();
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initArchiveSearch, { once: true });
    } else {
        initArchiveSearch();
    }
})();
